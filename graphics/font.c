void font_draw_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    if (c < 32 || c > 127) c = '?';
    const uint8_t *g = font[(uint8_t)c - 32];
    for (int row=0;row<8;row++){
        uint8_t bits=g[row];
        for (int col=0;col<8;col++){
        if (bits & (1<<col))
      		 fb_put_pixel(x+col, y+row, fg);
	else if (bg != COLOR_TRANSPARENT)
   		 fb_put_pixel(x+col, y+row, bg);
        }
    }
}

void font_draw_string(int x, int y, const char *s,
                      uint32_t fg, uint32_t bg) {
    int cx=x;
    while (*s) {
        if (*s=='\n') { cx=x; y+=FONT_HEIGHT+2; }
        else { font_draw_char(cx,y,*s,fg,bg); cx+=FONT_WIDTH+1; }
        s++;
    }
}
